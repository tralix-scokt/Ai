/* ==========================================================================
   demo.js — local, offline examples used only when Demo Mode is selected.

   These deterministic snippets are deliberately not described as AI output.
   The production transport remains assets/js/api/chat.js and never receives a
   browser-side secret. Demo streaming observes AbortSignal just like the API.
   ========================================================================== */

const DEMO_NOTICE = '\n\n---\n_Local demo example — this response was not generated by an AI model._';

export function demoResponseFor(input = '') {
  const text = String(input).trim();
  const lower = text.toLowerCase();
  let sample;

  if (/\b(explain|meaning|what is|how does|simpl(e|ify))\b/.test(lower)) {
    sample = `**A clear explanation — local example**\n\nA useful explanation starts with the main idea, introduces unfamiliar terms one at a time, then gives a concrete example. Paste the specific passage, concept, or error you want explained and JARVIS can help you explore it once a live AI backend is connected.`;
  } else if (/\b(code|coding|debug|function|javascript|python|program|build)\b/.test(lower)) {
    sample = `**A small coding example — local sample**\n\n\`\`\`js\nfunction greet(name) {\n  return \`Hello, \${name}!\`;\n}\n\nconsole.log(greet('world'));\n\`\`\`\n\nThis fixed example demonstrates the interface only. A connected model is needed to write or debug code for your specific task.`;
  } else if (/\b(summar(y|ize|ise)|tl;dr|recap)\b/.test(lower)) {
    sample = `**Summary workflow — local example**\n\n1. Identify the central point.\n2. Keep only the supporting details that change the meaning.\n3. End with the most useful takeaway.\n\nPaste text to summarize after connecting a live model. This sample does not analyze your message.`;
  } else if (/\b(open|website|web ?site|url|link|browser|safari)\b/.test(lower)) {
    sample = `I can help explain a URL or guide you through a website, but this web app cannot open or control other iPhone apps. Paste a link or page text here; a live model or supported tool will be needed to analyze its contents.\n\nFor now, this is a local capability example—not a real website lookup.`;
  } else if (/\b(plan|organize|schedule|steps|roadmap)\b/.test(lower)) {
    sample = `**A simple plan — local example**\n\n1. Define the outcome and a realistic deadline.\n2. Break the work into small, verifiable steps.\n3. Do the highest-impact step first.\n4. Review progress and adjust.\n\nThis is a fixed sample, not a plan generated from your personal context.`;
  } else if (/\b(hello|hi|hey|who are you|what can you do)\b/.test(lower)) {
    sample = `Systems nominal. I’m JARVIS, your assistant interface. In Demo Mode I can show local example replies, but I’m not connected to an AI model yet. Connect a secure backend to enable real conversations.`;
  } else {
    const excerpt = text.length > 96 ? `${text.slice(0, 93).trimEnd()}…` : text;
    sample = `I’ve received “${excerpt || 'your message'}”. This local example confirms that the composer, conversation history, and response display are working. It does not interpret the request; connect a live AI backend for real answers.`;
  }

  return `${sample}${DEMO_NOTICE}`;
}

function abortError() {
  const error = new Error('The demo response was stopped.');
  error.name = 'AbortError';
  return error;
}

function wait(ms, signal) {
  if (signal?.aborted) return Promise.reject(abortError());
  return new Promise((resolve, reject) => {
    const finish = () => {
      signal?.removeEventListener('abort', cancel);
      resolve();
    };
    const timer = setTimeout(finish, ms);
    const cancel = () => {
      clearTimeout(timer);
      signal?.removeEventListener('abort', cancel);
      reject(abortError());
    };
    signal?.addEventListener('abort', cancel, { once: true });
  });
}

/** Stream a deterministic local sample using the same delta contract as the API. */
export async function streamDemoReply({ input = '', signal, onDelta = () => {} } = {}) {
  const text = demoResponseFor(input);
  await wait(260, signal);

  let whole = '';
  for (let index = 0; index < text.length; index += 34) {
    if (signal?.aborted) throw abortError();
    const delta = text.slice(index, index + 34);
    whole += delta;
    onDelta(delta, whole);
    await wait(24, signal);
  }

  return { text: whole, model: 'Local demo', usage: null, status: 'demo', demo: true };
}
